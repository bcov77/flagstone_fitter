"""Explicit deterministic worst-case geometry and placement error bounds."""
from dataclasses import dataclass
import math
import numpy as np


@dataclass(frozen=True)
class StoneUncertainty:
    """Nonnegative bounds in layout length units, angle in radians.

    shape is an outward outline error bound, translation is a center-placement
    error bound, and rotation is an absolute angular placement error bound.
    These are user-supplied bounds, not estimates generated by the program.
    """
    shape: float = 0
    translation: float = 0
    rotation: float = 0

    def __post_init__(self):
        if not all(math.isfinite(x) and x >= 0 for x in (self.shape, self.translation, self.rotation)):
            raise ValueError('Uncertainty bounds must be finite and nonnegative')

    def margin(self, local_shape):
        """Maximum outward displacement relative to the modeled placement."""
        vertices = np.asarray(local_shape.exterior.coords)[:, :2]
        radius = float(np.linalg.norm(vertices, axis=1).max())
        angular_displacement = 2 * radius * math.sin(min(self.rotation, math.pi) / 2)
        return self.shape + self.translation + angular_displacement


def stone_margins(layout, uncertainties):
    """Compute per-stone margins; unspecified IDs receive zero margin."""
    if not set(uncertainties).issubset(layout.ids):
        raise ValueError('uncertainties contains an unknown stone ID')
    if not all(isinstance(value, StoneUncertainty) for value in uncertainties.values()):
        raise ValueError('uncertainties must contain StoneUncertainty values')
    return {sid: bounds.margin(layout.shapes[sid]) for sid, bounds in uncertainties.items()}


def parse_uncertainty_model(layout, data):
    """Validate complete, explicit component bounds and derive length margins.

    The versioned model requires an entry for every inventory ID, including
    currently inactive stones. It contains no default construction tolerances.
    """
    import numbers
    if not isinstance(data, dict) or data.get('uncertainty_version') != 1:
        raise ValueError('Unsupported uncertainty_version')
    if data.get('units') != layout.units:
        raise ValueError('Uncertainty units must match layout units')
    def bound(value):
        if isinstance(value, bool) or not isinstance(value, numbers.Real) or not math.isfinite(value) or value < 0:
            raise ValueError('Uncertainty bounds must be finite nonnegative numbers')
        return float(value)
    if 'patio' not in data:
        raise ValueError('Explicit patio uncertainty is required')
    patio = bound(data['patio'])
    items = data.get('stones')
    if not isinstance(items, dict) or set(items) != set(layout.ids):
        raise ValueError('Uncertainty model must include exactly every stone ID')
    uncertainty = {}
    for sid, entry in items.items():
        if not isinstance(entry, dict) or set(entry) != {'shape', 'translation', 'rotation'}:
            raise ValueError('Each stone requires shape, translation, and rotation bounds')
        uncertainty[sid] = StoneUncertainty(shape=bound(entry['shape']),
                                            translation=bound(entry['translation']),
                                            rotation=bound(entry['rotation']))
    return stone_margins(layout, uncertainty), patio


def verify_uncertainty_model(layout, model, margins, patio_margin):
    """Reject a saved model that does not reproduce the active margins."""
    if model is None:
        return
    expected, patio = parse_uncertainty_model(layout, model)
    if not isinstance(margins, dict) or set(margins) != set(expected):
        raise ValueError('Saved margins do not match the uncertainty model')
    # No fixed absolute slack: a tiny but explicit bound must not match zero
    # merely because the layout uses small coordinate units.
    if not np.isclose(patio, patio_margin, rtol=1e-12, atol=0):
        raise ValueError('Saved patio margin does not match the uncertainty model')
    if any(not np.isclose(expected[sid], margins[sid], rtol=1e-12, atol=0) for sid in expected):
        raise ValueError('Saved stone margins do not match the uncertainty model')
